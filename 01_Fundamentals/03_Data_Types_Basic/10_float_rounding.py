"""
Problem: Create a float variable and round it to specific decimal places.
"""

pi_value = 3.14159265359

print(f"Original Float: {pi_value}")

# Rounding to 2 decimal places
rounded_2 = round(pi_value, 2)
print(f"Rounded to 2 decimals: {rounded_2}")

# Rounding to 4 decimal places
rounded_4 = round(pi_value, 4)
print(f"Rounded to 4 decimals: {rounded_4}")